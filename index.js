// Основные символы
// Классы символов
/**
 * \d - цифра [0-9]
 * \w - буква, цифра, _ [A-Z,a-z,0-9_]
 * \s - пробельный символ
 * \D, \W, \S - ОТРИЦАНИЕ (НЕ ЦИФРА, НЕ БУКВА, НЕ ПРОБЕЛ)
 * . - ЛЮБОЙ СИМВОЛ КРОМЕ ПЕРЕВОДА СТРОКИ
 */

// Квантифакторы (количество)
/**
 * + - один и больше
 * * - ноль и больше
 * ? - ноль и один
 * {3} - ровно 3
 * {2 , 5} - от 2 до 5
 * {2, } - 2 и больше
 */

// Якоря
// ^ - начало строки
// $ - конец строки

// Группа и альтернация
/**
 * (...) - Группа
 * | - Или
 * [abc] - Любой из символов a,b,c
 * [^abc] - Любые символы кромме a,b,c
 * [a-z] - Диапозон
 * */

